def ensure_roles(db: Session) -> None:
    for name in ("analyst", "manager", "admin"):
        if not db.scalar(select(Role.id).where(Role.name == name)):
            db.add(Role(name=name))
    db.commit()


def _fill(db: Session, owner: User, name: str, desc: str, key: str, count: int, seed: int, analyze: bool) -> None:
    rng = random.Random(seed)
    s = ReviewSet(owner_id=owner.id, name=name, description=desc)
    db.add(s)
    db.flush()
    today = date.today()
    pool = PHRASES[key]
    for i in range(count):
        db.add(Review(set_id=s.id, text=pool[i % len(pool)] if i < len(pool) else rng.choice(pool), source="csv" if rng.random() < 0.7 else "manual",
                      rating=None, created_at=today - timedelta(days=rng.randint(0, 62))))
    db.commit()
    if analyze:
        job = analysis_service.create_job(db, s)
        analysis_service.run_job(job.id)


def seed_demo(db: Session) -> None:
    ensure_roles(db)
    if db.scalar(select(User.id).limit(1)):
        return
    roles = {r.name: r.id for r in db.scalars(select(Role))}
    pw = hash_password(DEMO_PASSWORD)
    users = []
    for email, name, role in DEMO_USERS:
        u = User(email=email, password_hash=pw, full_name=name, role_id=roles[role])
        db.add(u)
        users.append(u)
    db.commit()
    analyst = users[0]
    _fill(db, analyst, "Мобільний застосунок", "Відгуки з магазину застосунків", "app", 96, 11, True)
    _fill(db, analyst, "Інтернет-магазин", "Відгуки про доставку та товари", "shop", 54, 29, True)
    _fill(db, analyst, "Служба доставки", "Нові відгуки, ще не проаналізовані", "delivery", 12, 47, False)
    log.info("Створено демонстраційні дані")

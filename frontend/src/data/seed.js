// простий детермінований генератор псевдовипадкових чисел
function rng(seed) {
  let s = seed
  return () => {
    s = (s * 1664525 + 1013904223) % 4294967296
    return s / 4294967296
  }
}

const REF = new Date('2026-03-01T12:00:00')
const iso = (d) => d.toISOString().slice(0, 10)

function makeReviews(startId, count, topics, seed, analyzed, spanDays = 70) {
  const r = rng(seed)
  const pick = (a) => a[Math.floor(r() * a.length)]
  const out = []
  for (let i = 0; i < count; i++) {
    const x = r()
    const sentiment = x < 0.46 ? 'positive' : x < 0.7 ? 'neutral' : 'negative'
    const topic = pick(topics)
    const [text, kw] = pick(T[topic][sentiment])
    const d = new Date(REF)
    d.setDate(d.getDate() - Math.floor(r() * spanDays))
    const base = sentiment === 'neutral' ? 0.55 : 0.82
    out.push({
      id: startId + i,
      text,
      source: r() < 0.7 ? 'csv' : 'manual',
      rating: sentiment === 'positive' ? (r() < 0.7 ? 5 : 4) : sentiment === 'neutral' ? 3 : r() < 0.5 ? 1 : 2,
      created: iso(d),
      analysis: analyzed
        ? { sentiment, confidence: Math.min(0.99, +(base + r() * 0.16).toFixed(2)), topic, keywords: kw }
        : null,
    })
  }
  return out.sort((a, b) => b.created.localeCompare(a.created))
}

